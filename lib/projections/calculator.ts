import type { 年次予測 } from '@/types';

interface 年別月給 {
  年: number;
  月給: number;
  ボーナス額?: number;
}

interface 計算入力 {
  初期資産: number;
  年別月給リスト: 年別月給[];
  投資利回り: number;
  開始年: number;
  対象年数: number;
}

export function 年次予測を計算(入力: 計算入力): 年次予測[] {
  const { 初期資産, 年別月給リスト, 投資利回り, 開始年, 対象年数 } = 入力;
  const 予測結果: 年次予測[] = [];

  let 現在資産 = 初期資産;

  for (let 年度 = 0; 年度 < 対象年数; 年度++) {
    const 対象年 = 開始年 + 年度;

    // 対象年の月給・ボーナスを取得（最新の有効な値を使用）
    const 該当する給与情報 = 年別月給リスト
      .filter((g) => g.年 <= 対象年)
      .sort((a, b) => b.年 - a.年)[0];

    if (!該当する給与情報) {
      throw new Error(`年${対象年}の給与情報が見つかりません`);
    }

    const 月給 = 該当する給与情報.月給;
    const ボーナス額 = 該当する給与情報.ボーナス額 ?? 0;

    const 年間給与 = 月給 * 12;
    const 年収 = 年間給与 + ボーナス額;
    const 投資利益 = 現在資産 * 投資利回り;
    const 支出 = 0; // TODO: ライフイベントと予算から計算

    現在資産 = 現在資産 + 年収 - 支出 + 投資利益;

    予測結果.push({
      年: 対象年,
      年齢: {}, // TODO: 家族メンバーの生年月日から計算
      収入: 年収,
      支出: 支出,
      投資利益: 投資利益,
      資産: 現在資産,
      ライフイベント: [],
    });
  }

  return 予測結果;
}
